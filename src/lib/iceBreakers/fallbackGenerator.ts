export function generateFallbackQuestions(
  topic: string,
  mode: RoomModeId,
  lang: "en" | "ru" = "en"
): string[] {
  const templates = TEMPLATES[mode][lang];
  return templates.map((t) => t.replace(/\{topic\}/g, topic));
}
